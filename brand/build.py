"""Builds every logo asset from brand/paths.json (made by brand/trace.py).
Writes: brand/*.svg, public/icon.svg, public/brand/*.svg, src/components/brand.tsx. Then run: node brand/render.mjs"""
import json, re, os

P = json.load(open("brand/paths.json"))
DARK, BLUE = "#212933", "#005DD4"
r1 = lambda d: re.sub(r"-?\d+\.\d+", lambda m: f"{float(m.group()):.1f}".rstrip("0").rstrip("."), d)
m, w = P["mark"], P["word"]
for part in (m, w):
    part["dark"], part["blue"] = r1(part["dark"]), r1(part["blue"])
x0, y0 = min(m["x"], w["x"]), min(m["y"], w["y"])
W = round(max(m["x"] + m["w"], w["x"] + w["w"]) - x0, 1)
H = round(max(m["y"] + m["h"], w["y"] + w["h"]) - y0, 1)
mt = (round(m["x"] - x0, 1), round(m["y"] - y0, 1))
wt = (round(w["x"] - x0, 1), round(w["y"] - y0, 1))

def svg_mark(extra=""):
    return f'<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 {m["w"]} {m["h"]}"{extra}><path fill="{DARK}" d="{m["dark"]}"/><path fill="{BLUE}" d="{m["blue"]}"/></svg>'

def svg_logo(dark=DARK):
    return (f'<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 {W} {H}">'
            f'<g transform="translate({mt[0]} {mt[1]})"><path fill="{dark}" d="{m["dark"]}"/><path fill="{BLUE}" d="{m["blue"]}"/></g>'
            f'<g transform="translate({wt[0]} {wt[1]})"><path fill="{dark}" d="{w["dark"]}"/><path fill="{BLUE}" d="{w["blue"]}"/></g></svg>')

# Favicon: the mark on a white rounded square, so it shows on light and dark browser tabs.
pad = 46
side = max(m["w"], m["h"]) + 2 * pad
icon = (f'<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 {side} {side}">'
        f'<rect width="{side}" height="{side}" rx="{round(side * 0.22)}" fill="#fff"/>'
        f'<g transform="translate({round((side - m["w"]) / 2, 1)} {round((side - m["h"]) / 2, 1)})"><path fill="{DARK}" d="{m["dark"]}"/><path fill="{BLUE}" d="{m["blue"]}"/></g></svg>')

os.makedirs("public/brand", exist_ok=True)
for path, body in {
    "brand/scopeflow-mark.svg": svg_mark(), "brand/scopeflow-logo.svg": svg_logo(), "brand/scopeflow-logo-white.svg": svg_logo("#ffffff"),
    "public/brand/scopeflow-mark.svg": svg_mark(), "public/brand/scopeflow-logo.svg": svg_logo(), "public/icon.svg": icon,
}.items():
    open(path, "w").write(body + "\n")

tsx = f'''// Generated by brand/build.py from the official ScopeFlow logo (brand/scopeflow-logo-source.png). Don't edit by hand.
import type {{ SVGProps }} from "react";

const DARK = "{DARK}";
const BLUE = "{BLUE}";
const MARK_DARK = "{m["dark"]}";
const MARK_BLUE = "{m["blue"]}";
const WORD_DARK = "{w["dark"]}";
const WORD_BLUE = "{w["blue"]}";

type Props = SVGProps<SVGSVGElement> & {{ title?: string; tone?: "color" | "white" }};

/** The ScopeFlow symbol (two linked hooks). Square-ish; size it with width/height or CSS. */
export function LogoMark({{ title = "ScopeFlow", tone = "color", ...rest }}: Props) {{
  return (
    <svg viewBox="0 0 {m["w"]} {m["h"]}" role="img" aria-label={{title}} {{...rest}}>
      <path fill={{tone === "white" ? "#fff" : DARK}} d={{MARK_DARK}} />
      <path fill={{BLUE}} d={{MARK_BLUE}} />
    </svg>
  );
}}

/** The full ScopeFlow logo: symbol + wordmark. Aspect ratio {W}:{H}. */
export function LogoFull({{ title = "ScopeFlow", tone = "color", ...rest }}: Props) {{
  const ink = tone === "white" ? "#fff" : DARK;
  return (
    <svg viewBox="0 0 {W} {H}" role="img" aria-label={{title}} {{...rest}}>
      <g transform="translate({mt[0]} {mt[1]})">
        <path fill={{ink}} d={{MARK_DARK}} />
        <path fill={{BLUE}} d={{MARK_BLUE}} />
      </g>
      <g transform="translate({wt[0]} {wt[1]})">
        <path fill={{ink}} d={{WORD_DARK}} />
        <path fill={{BLUE}} d={{WORD_BLUE}} />
      </g>
    </svg>
  );
}}

export const LOGO_ASPECT = {round(W / H, 4)};
'''
open("src/components/brand.tsx", "w").write(tsx)
print("logo", W, H, "aspect", round(W / H, 3), "| tsx bytes", len(tsx), "| icon bytes", len(icon))
